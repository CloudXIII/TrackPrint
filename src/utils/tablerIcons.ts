function normalizeIconName(name: string | null | undefined): string {
  return String(name ?? '').replace(/^ti-/, '')
}

export function getTablerIcon(name: string | null | undefined): Component | null {
  return TABLER_ICONS[normalizeIconName(name)] ?? null
}
